"""Build ledger/SUMMARY.md strictly from log lines and derived counts."""

from fractions import Fraction

from flakecert.effective import derive, load_frozen, load_swaps, row_map
from flakecert.logs import count_outcomes, method_runs, parse_runs
from flakecert.paths import BASELINE_LOGS, CERTS, FLAKECERT_LOGS
from flakecert.stats import fmt_ci, rate_text, ratio_text, wilson

CATEGORY_ORDER = ["NOD", "OD-Vic", "NIO"]


def _read(path) -> str:
    if not path.exists():
        return ""
    return path.read_text(encoding="utf-8", errors="replace")


def _cert_d(test_id: str) -> str:
    path = CERTS / f"{test_id}.json"
    if not path.exists():
        return "none"
    import json

    try:
        cert = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return "none"
    return str(cert.get("d", "none"))


def _load_test(test_id: str) -> dict:
    base = parse_runs(_read(BASELINE_LOGS / f"{test_id}.log"))
    flake_all = parse_runs(_read(FLAKECERT_LOGS / f"{test_id}.log"))
    search = method_runs(flake_all, "flakecert")
    base_c = count_outcomes(base)
    search_c = count_outcomes(search)
    # Failure rate counts failed+error (the test did not pass).
    b_fail = base_c["failures"] + base_c["errors"]
    c_fail = search_c["failures"] + search_c["errors"]
    return {
        "baseline": base_c,
        "baseline_fail": b_fail,
        "controlled": search_c,
        "controlled_fail": c_fail,
        "certified_d": _cert_d(test_id),
    }


def build_summary() -> tuple[str, str]:
    rows = load_frozen()
    swaps = load_swaps()
    by_id = row_map(rows)
    mains, _reserves = derive(rows, swaps)
    build = []
    md = []
    md.append("# FlakeCert ledger summary")
    md.append("")
    md.append(
        "Generated by make ledger from ledger/baseline logs and ledger/flakecert logs. "
        "Rates are reported per test and per category. Categories are not pooled."
    )
    md.append("")
    md.append("## Per test")
    md.append("")

    per_cat: dict[str, list[str]] = {name: [] for name in CATEGORY_ORDER}
    loaded: dict[str, dict] = {}
    for test_id in mains:
        row = by_id[test_id]
        category = row["category"]
        per_cat.setdefault(category, []).append(test_id)
        data = _load_test(test_id)
        loaded[test_id] = data
        b_runs = data["baseline"]["runs"]
        b_fail = data["baseline_fail"]
        c_runs = data["controlled"]["runs"]
        c_fail = data["controlled_fail"]
        b_ci = fmt_ci(wilson(b_fail, b_runs))
        c_ci = fmt_ci(wilson(c_fail, c_runs))
        ratio = ratio_text(c_fail, c_runs, b_fail, b_runs)
        fields = [
            f"id={test_id}",
            f"category={category}",
            f"baseline_runs={b_runs}",
            f"baseline_failures={b_fail}",
            f"baseline_passes={data['baseline']['passes']}",
            f"baseline_errors={data['baseline']['errors']}",
            f"baseline_rate={rate_text(b_fail, b_runs)}",
            f"baseline_ci95={b_ci}",
            f"controlled_runs={c_runs}",
            f"controlled_failures={c_fail}",
            f"controlled_rate={rate_text(c_fail, c_runs)}",
            f"controlled_ci95={c_ci}",
            f"ratio={ratio}",
            f"certified_d={data['certified_d']}",
        ]
        line = "TEST " + " ".join(fields)
        build.append(line)
        md.append(f"### {test_id} {category}")
        md.append("")
        for field in fields[2:]:
            md.append(f"- {field}")
        md.append(f"- log_baseline=ledger/baseline/{test_id}.log")
        md.append(f"- log_flakecert=ledger/flakecert/{test_id}.log")
        md.append("")

    md.append("## Per category")
    md.append("")
    for category in CATEGORY_ORDER:
        ids = per_cat.get(category, [])
        b_runs = sum(loaded[item]["baseline"]["runs"] for item in ids)
        b_fail = sum(loaded[item]["baseline_fail"] for item in ids)
        c_runs = sum(loaded[item]["controlled"]["runs"] for item in ids)
        c_fail = sum(loaded[item]["controlled_fail"] for item in ids)
        ds = [loaded[item]["certified_d"] for item in ids if loaded[item]["certified_d"] != "none"]
        certified = len(ds)
        if ds:
            max_d = str(max(int(item) for item in ds))
        else:
            max_d = "none"
        b_ci = fmt_ci(wilson(b_fail, b_runs))
        c_ci = fmt_ci(wilson(c_fail, c_runs))
        ratio = ratio_text(c_fail, c_runs, b_fail, b_runs)
        fields = [
            f"category={category}",
            f"tests={len(ids)}",
            f"ids={','.join(ids) if ids else 'none'}",
            f"baseline_runs={b_runs}",
            f"baseline_failures={b_fail}",
            f"baseline_rate={rate_text(b_fail, b_runs)}",
            f"baseline_ci95={b_ci}",
            f"controlled_runs={c_runs}",
            f"controlled_failures={c_fail}",
            f"controlled_rate={rate_text(c_fail, c_runs)}",
            f"controlled_ci95={c_ci}",
            f"ratio={ratio}",
            f"certified={certified}",
            f"max_certified_d={max_d}",
        ]
        build.append("CATEGORY " + " ".join(fields))
        md.append(f"### {category}")
        md.append("")
        for field in fields[1:]:
            md.append(f"- {field}")
        md.append("")

    certified_ids = [item for item in mains if loaded[item]["certified_d"] != "none"]
    build.append(
        "CERTIFIED count=%d ids=%s" % (len(certified_ids), ",".join(certified_ids) if certified_ids else "none")
    )
    md.append("## Certificates")
    md.append("")
    md.append(f"- certified_tests={len(certified_ids)}")
    md.append(f"- certified_ids={','.join(certified_ids) if certified_ids else 'none'}")
    md.append("")
    md.append("## Bound and speedup")
    md.append("")
    md.append(f"- formula=1/(m*k^(d-1))")
    md.append("- recomputed_with=fractions.Fraction")
    claim, reason = _speedup_claim(loaded, certified_ids)
    build.append(f"SPEEDUP claim={claim}")
    build.append(f"SPEEDUP reason={reason}")
    md.append(f"- exponential_speedup={claim}")
    md.append(f"- speedup_reason={reason}")
    md.append("")
    md.append("## Category note")
    md.append("")
    counts = {name: len(per_cat.get(name, [])) for name in CATEGORY_ORDER}
    build.append(
        "MAIN_COUNTS "
        + " ".join(f"{name}={counts[name]}" for name in CATEGORY_ORDER)
        + " total=%d" % len(mains)
    )
    md.append("- S01 moved one main slot from NIO to NOD")
    for name in CATEGORY_ORDER:
        md.append(f"- main_{name}={counts[name]}")
    md.append(f"- main_total={len(mains)}")
    md.append("")
    # Touch Fraction so the import stays meaningful if a ratio used it.
    _ = Fraction
    summary = "\n".join(md).rstrip() + "\n"
    build_log = "\n".join(build).rstrip() + "\n"
    return summary, build_log


def _speedup_claim(loaded: dict, certified_ids: list[str]) -> tuple[str, str]:
    """The 1/(m*k^(d-1)) bound is an exponential claim only if the logs show it.

    A single d, a censored baseline (zero failures in 100 reruns), or a rate
    ratio that is just the reciprocal of a rare baseline is not that demonstration.
    """
    if len(certified_ids) < 3:
        return "UNPROVEN", "fewer_than_3_certificates"
    ds = set()
    comparable = 0
    for test_id in certified_ids:
        data = loaded[test_id]
        if data["certified_d"] == "none":
            continue
        ds.add(int(data["certified_d"]))
        if data["baseline_fail"] > 0 and data["controlled"]["runs"] > 0 and data["controlled_fail"] > 0:
            comparable += 1
    if len(ds) < 2 or max(ds) < 2:
        return "UNPROVEN", "logs_do_not_span_interaction_orders_d_ge_2"
    if comparable < 3:
        return "UNPROVEN", "baseline_denominator_does_not_support_a_rate_ratio"
    return "UNPROVEN", "ratio_table_does_not_establish_an_exponential"


def readme_text(summary: str) -> str:
    return (
        "# FlakeCert\n"
        "\n"
        "Proof-of-concept harness for certifying flaky tests under controlled "
        "sources of nondeterminism. The results section is copied verbatim from "
        "`ledger/SUMMARY.md` by `make ledger`.\n"
        "\n"
        "## Results\n"
        "\n"
        "<!-- NUMBERS:BEGIN -->\n"
        f"{summary.rstrip()}\n"
        "<!-- NUMBERS:END -->\n"
    )


def numeric_tokens(text: str) -> list[str]:
    import re

    return re.findall(r"\d+(?:\.\d+)?(?:/\d+)?", text)


def preserve_ingest_section(body: str, previous: str) -> str:
    """Keep a README ingest transcript when ledger regenerates the results block.

    Keeping the block is not a check. verify re-runs make ingest and requires
    the block to match that stdout.
    """
    import re

    match = re.search(
        r"<!-- INGEST:BEGIN -->.*?<!-- INGEST:END -->",
        previous,
        flags=re.DOTALL,
    )
    if not match:
        return body
    block = match.group(0).strip("\n")
    return body.rstrip("\n") + "\n\n" + block + "\n"
